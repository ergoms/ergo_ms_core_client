function collectShellIconNames(map) {
  const files = [path.join(clientRoot, 'src/config/coreIconNames.js')]
  for (const dir of ['src/components/menu', 'src/components/header']) {
    const abs = path.join(clientRoot, dir)
    if (!fs.existsSync(abs)) continue
    for (const entry of fs.readdirSync(abs, { recursive: true })) {
      const name = String(entry)
      if (name.endsWith('.vue') || name.endsWith('.js')) {
        files.push(path.join(abs, name))
      }
    }
  }
  const source = files.map((file) => fs.readFileSync(file, 'utf8')).join('\n')
  return Object.keys(map)
    .filter((name) => source.includes(`'${name}'`) || source.includes(`"${name}"`))
    .sort()
}

function writeCoreIconLoaders(iconMap) {
  const names = collectShellIconNames(iconMap)
  const iconRoot = '../../../../virtual_env/npm/node_modules/@lucide/vue/dist/esm/icons'
  const body = [
    '/**',
    ' * AUTO-GENERATED by scripts/generate-lucide-icon-map.js — do not edit.',
    ' * Иконки оболочки. Остальные глифы грузит lucideIconGlob.js по первому запросу.',
    ` * Icons: ${names.length}`,
    ' */',
    '',
    'export const CORE_ICON_LOADERS = Object.freeze({',
    ...names.map((name) => {
      const file = iconMap[name]
      return `  ${JSON.stringify(name)}: () => import(${JSON.stringify(`${iconRoot}/${file}.mjs`)}),`
    }),
    '})',
    '',
  ].join('\n')
  if (fs.existsSync(coreOutputPath) && fs.readFileSync(coreOutputPath, 'utf8') === body) {
    console.log(`[SKIP] lucideCoreIcons.generated.js: ${names.length} icons, содержимое не изменилось`)
    return
  }
  fs.writeFileSync(coreOutputPath, body, 'utf8')
  console.log(`[OK] lucideCoreIcons.generated.js: ${names.length} icons`)
}

/**
 * Имена, которые меню, мост и статический хром реально рисуют.
 * Сборка кладёт их файлы в один чанк, чтобы боковое меню не открывало
 * отдельный HTTP-запрос на каждый глиф. Редкие имена остаются в glob.
 */
function collectReferencedIconFiles(iconMap) {
  const roots = [
    path.join(clientRoot, 'src'),
    path.resolve(clientRoot, '../api/src'),
    path.resolve(clientRoot, '../../modules'),
  ]
  const { names, stats } = scanIconNames(roots, { cachePath: iconScanCachePath, projectRoot })
  console.log(
    `[INFO] Обход исходников для иконок: ${stats.files} файлов, прочитано ${stats.read}, ${stats.ms} мс`,
  )

  const files = new Set()

  function remember(rawName) {
    if (!rawName) {
      return
    }
    let name = rawName.trim()
    if (!name || name.endsWith('Icon') || name.startsWith('Lucide')) {
      return
    }
    if (name.includes('-') || name.includes('_')) {
      name = name
        .split(/[-_]/)
        .filter(Boolean)
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
        .join('')
    }
    const file = iconMap[name]
    if (file) {
      files.add(file)
    }
  }

  for (const name of names) {
    remember(name)
  }
  for (const name of MENU_ICON_NAMES_FROM_DATABASE) {
    remember(name)
  }

  return [...files].sort()
}

function writeMenuIconLoaders(iconMap, files) {
  const iconRoot = '../../../../virtual_env/npm/node_modules/@lucide/vue/dist/esm/icons'
  const fileSet = new Set(files)
  const names = Object.keys(iconMap)
    .filter((name) => fileSet.has(iconMap[name]))
    .sort()
  const body = [
    '/**',
    ' * AUTO-GENERATED by scripts/generate-lucide-icon-map.js — do not edit.',
    ' * Глифы меню и оболочки. Неизвестный глиф по-прежнему идёт через lucideIconGlob.js.',
    ` * Icons: ${names.length}`,
    ' */',
    '',
    'export const MENU_ICON_LOADERS = Object.freeze({',
    ...names.map((name) => {
      const file = iconMap[name]
      return `  ${JSON.stringify(name)}: () => import(${JSON.stringify(`${iconRoot}/${file}.mjs`)}),`
    }),
    '})',
    '',
  ].join('\n')
  if (fs.existsSync(menuLoadersOutputPath) && fs.readFileSync(menuLoadersOutputPath, 'utf8') === body) {
    console.log(`[SKIP] lucideMenuIcons.generated.js: ${names.length} icons, содержимое не изменилось`)
    return
  }
  fs.writeFileSync(menuLoadersOutputPath, body, 'utf8')
  console.log(`[OK] lucideMenuIcons.generated.js: ${names.length} icons`)
}

function writeMenuIconFiles(iconMap) {
  const files = collectReferencedIconFiles(iconMap)
  writeMenuIconLoaders(iconMap, files)
  const content = `${JSON.stringify(files, null, 2)}\n`
  if (fs.existsSync(menuFilesOutputPath) && fs.readFileSync(menuFilesOutputPath, 'utf8') === content) {
    console.log(`[SKIP] lucideMenuIconFiles.generated.json: ${files.length} files, содержимое не изменилось`)
    return
  }
  fs.writeFileSync(menuFilesOutputPath, content, 'utf8')
  console.log(`[OK] lucideMenuIconFiles.generated.json: ${files.length} files`)
}
