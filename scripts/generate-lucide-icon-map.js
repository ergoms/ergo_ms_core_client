/**
 * Генерирует lucideIconFiles.generated.js — PascalCase → kebab file
 * из barrel @lucide/vue (алиасы Home→house и т.п.).
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const clientRoot = path.resolve(__dirname, '..')
const outputPath = path.join(clientRoot, 'src/js/lucideIconFiles.generated.js')
const coreOutputPath = path.join(clientRoot, 'src/js/lucideCoreIcons.generated.js')

const require = createRequire(import.meta.url)

function resolveLucideBarrel() {
  try {
    const pkgJson = require.resolve('@lucide/vue/package.json')
    const pkgDir = path.dirname(pkgJson)
    const barrel = path.join(pkgDir, 'dist/esm/lucide-vue.mjs')
    if (fs.existsSync(barrel)) {
      return barrel
    }
  } catch {
    /* fall through */
  }

  const fallback = path.resolve(
    clientRoot,
    '../../virtual_env/npm/node_modules/@lucide/vue/dist/esm/lucide-vue.mjs',
  )
  if (fs.existsSync(fallback)) {
    return fallback
  }
  throw new Error('[generate-lucide-icon-map] @lucide/vue barrel not found')
}

function buildMap(barrelSource) {
  /** @type {Record<string, string>} */
  const map = {}
  for (const line of barrelSource.split(/\r?\n/)) {
    const fileMatch = line.match(/from '\.\/icons\/([^']+)\.mjs'/)
    if (!fileMatch) {
      continue
    }
    const file = fileMatch[1]
    const names = [...line.matchAll(/default as (\w+)/g)].map((m) => m[1])
    for (const name of names) {
      if (name.endsWith('Icon') || name.startsWith('Lucide')) {
        continue
      }
      map[name] = file
    }
  }
  return map
}

const barrelPath = resolveLucideBarrel()
const map = buildMap(fs.readFileSync(barrelPath, 'utf8'))
const keys = Object.keys(map).sort()

const lines = [
  '/**',
  ' * AUTO-GENERATED by scripts/generate-lucide-icon-map.js — do not edit.',
  ` * Icons: ${keys.length}`,
  ' */',
  '',
  'export const LUCIDE_ICON_FILES = Object.freeze({',
  ...keys.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(map[name])},`),
  '})',
  '',
  'export const LUCIDE_ICON_NAMES = Object.freeze(Object.keys(LUCIDE_ICON_FILES))',
  '',
]

const content = lines.join('\n')
if (fs.existsSync(outputPath) && fs.readFileSync(outputPath, 'utf8') === content) {
  console.log(`[SKIP] lucideIconFiles.generated.js: ${keys.length} icons, содержимое не изменилось`)
} else {
  fs.writeFileSync(outputPath, content, 'utf8')
  console.log(`[OK] lucideIconFiles.generated.js: ${keys.length} icons`)
}

writeCoreIconLoaders(map)

function collectShellIconNames(map) {
  const files = [path.join(clientRoot, 'src/config/coreIconNames.js')]
  for (const dir of ['src/components/menu', 'src/components/header']) {
    const abs = path.join(clientRoot, dir)
    if (!fs.existsSync(abs)) continue
    for (const entry of fs.readdirSync(abs, { recursive: true })) {
      const name = String(entry)
      if (name.endsWith('.vue') || name.endsWith('.js')) {
        files.push(path.join(abs, name))
      }
    }
  }
  const source = files.map((file) => fs.readFileSync(file, 'utf8')).join('\n')
  return Object.keys(map)
    .filter((name) => source.includes(`'${name}'`) || source.includes(`"${name}"`))
    .sort()
}

function writeCoreIconLoaders(iconMap) {
  const names = collectShellIconNames(iconMap)
  const iconRoot = '../../../../virtual_env/npm/node_modules/@lucide/vue/dist/esm/icons'
  const body = [
    '/**',
    ' * AUTO-GENERATED by scripts/generate-lucide-icon-map.js — do not edit.',
    ' * Иконки оболочки. Остальные глифы грузит lucideIconGlob.js по первому запросу.',
    ` * Icons: ${names.length}`,
    ' */',
    '',
    'export const CORE_ICON_LOADERS = Object.freeze({',
    ...names.map((name) => {
      const file = iconMap[name]
      return `  ${JSON.stringify(name)}: () => import(${JSON.stringify(`${iconRoot}/${file}.mjs`)}),`
    }),
    '})',
    '',
  ].join('\n')
  if (fs.existsSync(coreOutputPath) && fs.readFileSync(coreOutputPath, 'utf8') === body) {
    console.log(`[SKIP] lucideCoreIcons.generated.js: ${names.length} icons, содержимое не изменилось`)
    return
  }
  fs.writeFileSync(coreOutputPath, body, 'utf8')
  console.log(`[OK] lucideCoreIcons.generated.js: ${names.length} icons`)
}
